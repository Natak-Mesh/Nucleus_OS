#!/bin/bash
set -e
                                                                                                          

#       ..        .....        ...       
#       ....     ......       ....      
#       .......... ...       .....       
#       ........    ..      ......       
#       ......      ..     .......       
#       .....       ...  .........       
#       ....        .....     ....      
#       ...         ....        ..   

#############################################
#        N A T A K   -   Nucleus OS         #
#                                           #
#      Configuration File Generation        #
#############################################


# Source configuration
source /etc/nucleus/mesh.conf

# Calculate frequency from channel (2.4GHz)
MESH_FREQ=$((2407 + ($MESH_CHANNEL * 5)))

# Calculate subnets from IP addresses
MESH_SUBNET=$(echo $MESH_IP | cut -d'.' -f1-3).0/24
BR_LAN_SUBNET=$(echo $BR_LAN_IP | cut -d'.' -f1-3).0/24
ETH0_SUBNET=$(echo $ETH0_STATIC_IP | cut -d'.' -f1-3).0/24

# Generate eth0 network config (default WAN mode)
cat > /etc/systemd/network/40-eth0-lan.network <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Default mode: WAN (DHCP client)
# Use /opt/nucleus/bin/eth0-mode.sh to switch between WAN/LAN modes
# ============================================================

[Match]
Name=eth0

[Network]
DHCP=ipv4
IPv4Forwarding=yes
EOF

# Generate wlan1 network config
cat > /etc/systemd/network/10-wlan1.network <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MESH_IP, MESH_IPV6_LL
# ============================================================

[Match]
Name=wlan1

[Network]
Address=${MESH_IP}/24
Address=${MESH_IPV6_LL}/64
LinkLocalAddressing=no
IPv6AcceptRA=no
ConfigureWithoutCarrier=yes
EOF

# Generate br-lan network config
cat > /etc/systemd/network/21-brlan.network <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: BR_LAN_IP, BR_LAN_IPV6_LL, MESH_IP
# ============================================================

[Match]
Name=br-lan

[Network]
Address=${BR_LAN_IP}/24
Address=${BR_LAN_IPV6_LL}/64
LinkLocalAddressing=no
IPv6AcceptRA=no
DHCPServer=yes

[DHCPServer]
PoolOffset=10
PoolSize=50
EmitDNS=yes
DNS=8.8.8.8
EmitRouter=yes
EOF

# Generate hostapd config
cat > /etc/hostapd/hostapd.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: AP_NAME, AP_CHANNEL, AP_PASSWORD
# ============================================================

interface=wlan0
ssid=$AP_NAME
hw_mode=a
channel=$AP_CHANNEL
auth_algs=1
wmm_enabled=1
wpa=2
wpa_passphrase=$AP_PASSWORD
wpa_key_mgmt=WPA-PSK
rsn_pairwise=CCMP
EOF

# Generate wpa_supplicant config
cat > /etc/wpa_supplicant/wpa_supplicant-wlan1-encrypt.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MESH_NAME, MESH_CHANNEL, MESH_FREQ, MESH_PASSWORD
# ============================================================

ctrl_interface=/var/run/wpa_supplicant
update_config=1
ap_scan=0
country=US

network={
    ssid="$MESH_NAME"
    mode=5
    frequency=$MESH_FREQ
    key_mgmt=SAE
    psk="$MESH_PASSWORD"
    mesh_fwding=0
    ieee80211w=2
}
EOF

# Generate babeld config
cat > /etc/babeld.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MESH_SUBNET, BR_LAN_SUBNET
# ============================================================

# Babeld Routing Configuration for Natak Mesh
# This configuration enables proper route redistribution across the mesh network

# Kernel route installation
import-table 254
export-table 254

# Local monitoring interface (read-only)
local-port 33123

# Wireless mesh interface (wlan1)
interface wlan1 type wireless link-quality true split-horizon false rxcost 256 hello-interval 4 update-interval 16

# Wired bridge interface (br-lan)
interface br-lan type wired rxcost 96 hello-interval 4

# Block router LAN networks from being redistributed (prevents asymmetric routing)
redistribute ip 192.168.0.0/16 deny

# Redistribute local mesh network
redistribute ip ${MESH_SUBNET} allow

# Redistribute br-lan network
redistribute ip ${BR_LAN_SUBNET} allow

# Redistribute default route for internet gateway sharing
redistribute ip 0.0.0.0/0 allow

# Block default local address /32 export (must come after allow rules)
redistribute local deny

# Default deny to prevent redistributing unwanted routes
redistribute deny
EOF

# Generate nginx vhost for the web UI .local hostname
# ============================================================
# Lets users reach the Nucleus web UI at http://<serial>-nucleus.local
# (no :5000 needed) by matching the mDNS/Avahi hostname's Host: header
# and proxying to the Flask app on 127.0.0.1:5000.
#
# Coexistence with OpenTAKServer (OTS): OTS owns port 80 with its own
# nginx vhosts (ots_http etc.) and remains the *default* responder for
# port 80 (i.e. access by IP). nginx routes by the Host: header, so a
# request for <serial>-nucleus.local matches THIS block while everything
# else (IP access, OTS hostnames) falls through to the OTS blocks,
# untouched. The filename is prefixed "zzz-" so it sorts AFTER the
# ots_* files in sites-enabled/, ensuring OTS keeps port-80 default.
# ============================================================
NUCLEUS_HOSTNAME="$(hostname)"

# Generate our own self-signed TLS cert for <hostname>.local (idempotent).
# Needed because phones/modern browsers force HTTPS (HSTS / auto-upgrade), so
# the .local hostname is requested over port 443. We use our OWN cert (not
# OTS's) so this works identically on OTS and non-OTS nodes. Browsers will
# show a "not secure" warning (expected for a self-signed LAN .local host).
NUCLEUS_CERT_DIR=/etc/nucleus/certs
NUCLEUS_CERT="${NUCLEUS_CERT_DIR}/nucleus-web.crt"
NUCLEUS_KEY="${NUCLEUS_CERT_DIR}/nucleus-web.key"
mkdir -p "${NUCLEUS_CERT_DIR}"
if [ ! -f "${NUCLEUS_CERT}" ] || [ ! -f "${NUCLEUS_KEY}" ]; then
    openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
        -keyout "${NUCLEUS_KEY}" \
        -out "${NUCLEUS_CERT}" \
        -subj "/CN=${NUCLEUS_HOSTNAME}.local" \
        -addext "subjectAltName=DNS:${NUCLEUS_HOSTNAME}.local" 2>/dev/null \
        && echo "Generated self-signed cert for ${NUCLEUS_HOSTNAME}.local" \
        || echo "WARNING: failed to generate self-signed cert"
    chmod 600 "${NUCLEUS_KEY}" 2>/dev/null || true
fi

cat > /etc/nginx/sites-available/zzz-nucleus-web <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Routes http(s)://${NUCLEUS_HOSTNAME}.local -> Nucleus web UI (Flask :5000)
# Coexists with OpenTAKServer's nginx vhosts via Host-header / SNI routing.
# ============================================================

# HTTP (port 80) - matched by Host header
server {
    listen 80;
    listen [::]:80;

    server_name ${NUCLEUS_HOSTNAME}.local;

    # OpenVLM voice — WebSocket audio bridge to the voice daemon (soft PTT).
    location /voice-ws {
        proxy_pass http://127.0.0.1:5557;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        proxy_buffering off;
    }

    location / {
        proxy_pass http://127.0.0.1:5000;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}

# HTTPS (port 443) - matched by SNI. Phones/modern browsers force HTTPS, so
# this block is what actually serves the .local hostname on mobile. Uses our
# OWN self-signed cert. NOT a default_server, so OTS's 443 vhost is untouched
# and remains the responder for IP/OTS-hostname HTTPS requests.

server {
    listen 443 ssl;
    listen [::]:443 ssl;

    server_name ${NUCLEUS_HOSTNAME}.local;

    ssl_certificate ${NUCLEUS_CERT};
    ssl_certificate_key ${NUCLEUS_KEY};

    # OpenVLM voice — WebSocket audio bridge to the voice daemon (soft PTT).
    # This is the path phones actually use (they force HTTPS -> wss).
    location /voice-ws {
        proxy_pass http://127.0.0.1:5557;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        proxy_buffering off;
    }

    location / {
        proxy_pass http://127.0.0.1:5000;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF


# Enable the vhost (idempotent symlink)
ln -sf /etc/nginx/sites-available/zzz-nucleus-web /etc/nginx/sites-enabled/zzz-nucleus-web

# Validate and reload nginx so the change takes effect
if nginx -t 2>/dev/null; then
    systemctl reload nginx 2>/dev/null || systemctl restart nginx 2>/dev/null || true
    echo "nginx vhost generated: http://${NUCLEUS_HOSTNAME}.local -> web UI"
else
    echo "WARNING: nginx config test failed - vhost written but not reloaded"
fi

# Enable/disable CoT bridge service based on config
if [ "${COT_BRIDGE_ENABLED,,}" = "true" ]; then
    systemctl enable cot-bridge.service 2>/dev/null || true
    echo "CoT bridge service enabled (will start on boot)"
else
    systemctl disable cot-bridge.service 2>/dev/null || true
    echo "CoT bridge service disabled"
fi

echo "Configuration files generated successfully."
