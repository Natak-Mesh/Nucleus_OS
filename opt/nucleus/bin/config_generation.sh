#############################################
#        N A T A K   -   Nucleus OS         #
#          Drone Companion Computer         #
#                                           #
#      Configuration File Generation        #
#############################################


# Source configuration
source /etc/nucleus/mesh.conf

# Calculate frequency from channel (2.4GHz)
MESH_FREQ=$((2407 + ($MESH_CHANNEL * 5)))

# Calculate subnets from IP addresses
MESH_SUBNET=$(echo $MESH_IP | cut -d'.' -f1-3).0/24
BR_LAN_SUBNET=$(echo $BR_LAN_IP | cut -d'.' -f1-3).0/24
ETH0_SUBNET=$(echo $ETH0_STATIC_IP | cut -d'.' -f1-3).0/24

# Generate eth0 network config (default WAN mode)
cat > /etc/systemd/network/40-eth0-lan.network <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Default mode: WAN (DHCP client)
# Use /opt/nucleus/bin/eth0-mode.sh to switch between WAN/LAN modes
# ============================================================

[Match]
Name=eth0

[Network]
DHCP=ipv4
IPv4Forwarding=yes
EOF

# Generate wlan1 network config
cat > /etc/systemd/network/10-wlan1.network <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MESH_IP, MESH_IPV6_LL
# ============================================================

[Match]
Name=wlan1

[Network]
Address=${MESH_IP}/24
Address=${MESH_IPV6_LL}/64
LinkLocalAddressing=no
IPv6AcceptRA=no
ConfigureWithoutCarrier=yes
EOF

# Generate br-lan network config
cat > /etc/systemd/network/21-brlan.network <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: BR_LAN_IP, BR_LAN_IPV6_LL, MESH_IP
# ============================================================

[Match]
Name=br-lan

[Network]
Address=${BR_LAN_IP}/24
Address=${BR_LAN_IPV6_LL}/64
LinkLocalAddressing=no
IPv6AcceptRA=no
DHCPServer=yes

[DHCPServer]
PoolOffset=10
PoolSize=50
EmitDNS=yes
DNS=8.8.8.8
EmitRouter=yes
EOF

# Generate hostapd config
cat > /etc/hostapd/hostapd.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: AP_NAME, AP_CHANNEL, AP_PASSWORD
# ============================================================

interface=wlan0
ssid=$AP_NAME
hw_mode=a
channel=$AP_CHANNEL
auth_algs=1
wmm_enabled=1
wpa=2
wpa_passphrase=$AP_PASSWORD
wpa_key_mgmt=WPA-PSK
rsn_pairwise=CCMP
EOF

# Generate wpa_supplicant config
cat > /etc/wpa_supplicant/wpa_supplicant-wlan1-encrypt.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MESH_NAME, MESH_CHANNEL, MESH_FREQ, MESH_PASSWORD
# ============================================================

ctrl_interface=/var/run/wpa_supplicant
update_config=1
ap_scan=0
country=US

network={
    ssid="$MESH_NAME"
    mode=5
    frequency=$MESH_FREQ
    key_mgmt=SAE
    psk="$MESH_PASSWORD"
    mesh_fwding=0
    ieee80211w=2
}
EOF

# Generate babeld config
cat > /etc/babeld.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MESH_SUBNET, BR_LAN_SUBNET
# ============================================================

# Babeld Routing Configuration for Natak Mesh
# This configuration enables proper route redistribution across the mesh network

# Kernel route installation
import-table 254
export-table 254

# Local monitoring interface (read-only)
local-port 33123

# Wireless mesh interface (wlan1)
interface wlan1 type wireless link-quality true split-horizon false rxcost 256 hello-interval 4 update-interval 16

# Wired bridge interface (br-lan)
interface br-lan type wired rxcost 96 hello-interval 4

# Block router LAN networks from being redistributed (prevents asymmetric routing)
redistribute ip 192.168.0.0/16 deny

# Redistribute local mesh network
redistribute ip ${MESH_SUBNET} allow

# Redistribute br-lan network
redistribute ip ${BR_LAN_SUBNET} allow

# Redistribute default route for internet gateway sharing
redistribute ip 0.0.0.0/0 allow

# Block default local address /32 export (must come after allow rules)
redistribute local deny

# Default deny to prevent redistributing unwanted routes
redistribute deny
EOF

# Generate mavlink-router config
# Bridges the ArduPilot flight controller UART to UDP over the mesh.
# Mode=Server means mavlink-router listens for GCS clients rather than
# pushing to a fixed address — any ground station on the mesh can connect
# to MESH_IP:MAVLINK_UDP_PORT, and multiple GCS can attach at once.
#
# Only generated when DRONE_ENABLED=true. mavlink-router.service carries
# ConditionPathExists=/etc/mavlink-router/main.conf, so removing this file
# is what keeps the daemon from running on nodes that are not part of the
# drone mesh — no process, no UART held, no CPU used.
if [ "${DRONE_ENABLED}" = "true" ]; then
mkdir -p /etc/mavlink-router
cat > /etc/mavlink-router/main.conf <<EOF
# ============================================================
# This file is dynamically generated by config_generation.sh
# Do not edit manually - changes will be overwritten
# Configuration variables sourced from /etc/nucleus/mesh.conf
# Variables used: MAVLINK_SERIAL, MAVLINK_BAUD, MAVLINK_UDP_PORT
# ============================================================

[General]
TcpServerPort = 0
ReportStats = false
MavlinkDialect = ardupilotmega

[UartEndpoint drone_fc]
Device = ${MAVLINK_SERIAL}
Baud = ${MAVLINK_BAUD}

[UdpEndpoint ground]
Mode = Server
Address = 0.0.0.0
Port = ${MAVLINK_UDP_PORT}
EOF

# Optional push endpoint. The server above waits for a GCS to speak first,
# which means nothing crosses the mesh until the ground station sends a
# packet. Setting MAVLINK_GCS_IP adds a push endpoint that streams to that
# address unprompted, so telemetry flows as soon as both nodes are up.
#
# This build of mavlink-router spells the push mode "Normal". "Client" is
# rejected at parse time and the daemon exits with:
#     Unknown 'mode' key: Client
# Do not "correct" Normal to Client.
if [ -n "${MAVLINK_GCS_IP}" ]; then
cat >> /etc/mavlink-router/main.conf <<EOF

[UdpEndpoint gcs_push]
Mode = Normal
Address = ${MAVLINK_GCS_IP}
Port = ${MAVLINK_UDP_PORT}
EOF
fi

    systemctl enable mavlink-router.service >/dev/null 2>&1 || true

    # Verify the UART is ready for the flight controller link.
    # The Pi's PL011 UART (/dev/ttyAMA0) is claimed by the Bluetooth controller
    # by default, and a serial console + login prompt sit on GPIO14/15. All of
    # that has to be undone before the FC link works. drone-uart-setup.sh does
    # it. See docs/drone/uart-setup.md for the full explanation.
    BOOT_CONFIG=/boot/firmware/config.txt
    [ -f "$BOOT_CONFIG" ] || BOOT_CONFIG=/boot/config.txt

    BOOT_CMDLINE=/boot/firmware/cmdline.txt
    [ -f "$BOOT_CMDLINE" ] || BOOT_CMDLINE=/boot/cmdline.txt

    UART_WARN=0
    if [ -f "$BOOT_CONFIG" ]; then
        grep -q '^enable_uart=1' "$BOOT_CONFIG" || UART_WARN=1
        grep -q '^dtoverlay=disable-bt' "$BOOT_CONFIG" || UART_WARN=1
    else
        UART_WARN=1
    fi

    # A serial console on GPIO14/15 transmits kernel output into the FC's RX pin.
    if [ -f "$BOOT_CMDLINE" ] && \
       grep -qE 'console=(serial0|ttyAMA0|ttyS0)' "$BOOT_CMDLINE"; then
        UART_WARN=1
    fi

    # /dev/ttyAMA0 missing means the PL011 is still bound to Bluetooth.
    [ -e /dev/ttyAMA0 ] || UART_WARN=1

    if [ "$UART_WARN" -eq 1 ]; then
        echo ""
        echo "=================================================="
        echo "  WARNING: UART not configured for the FC link"
        echo "=================================================="
        echo "  Run:"
        echo "    sudo /opt/nucleus/bin/drone-uart-setup.sh"
        echo "    sudo reboot"
        echo ""
        echo "  Then verify with:"
        echo "    python3 /opt/nucleus/drone/fc-link-check.py"
        echo ""
        echo "  Until this is done, mavlink-router cannot open"
        echo "  /dev/ttyAMA0 and the drone will not be controllable."
        echo "  Details: docs/drone/uart-setup.md"
        echo "=================================================="
        echo ""
    fi

    # ------------------------------------------------------------
    # Camera preflight check (warn-only, never edits boot config)
    # ------------------------------------------------------------
    # Unlike a regular Pi 4/5 (camera_auto_detect=1 just works), a Compute
    # Module has no camera EEPROM and needs the sensor declared explicitly,
    # on the correct CSI port. The right config is board-specific, and a bad
    # boot config on a flight platform is a brick risk, so we DETECT AND WARN
    # rather than write config.txt. See docs/drone/drone-hardware.md.
    if [ "${CAMERA_ENABLED}" = "true" ]; then
        CAM_WARN=0
        CAM_MSG=""
        SENSOR="${CAMERA_SENSOR:-imx708}"
        CSI_PORT="${CAMERA_CSI_PORT:-cam0}"

        MODEL=""
        [ -f /proc/device-tree/model ] && MODEL="$(tr -d '\0' < /proc/device-tree/model)"

        case "$MODEL" in
            *"Compute Module"*)
                # CM4/CM5: explicit overlay + regulator, no auto-detect.
                if [ -f "$BOOT_CONFIG" ]; then
                    grep -q "^dtoverlay=${SENSOR},${CSI_PORT}" "$BOOT_CONFIG" || {
                        CAM_WARN=1; CAM_MSG="${CAM_MSG}    dtoverlay=${SENSOR},${CSI_PORT}\n"; }
                    grep -q "^dtparam=i2c_vc=on" "$BOOT_CONFIG" || {
                        CAM_WARN=1; CAM_MSG="${CAM_MSG}    dtparam=i2c_vc=on\n"; }
                    grep -q "^dtparam=${CSI_PORT}_reg=on" "$BOOT_CONFIG" || {
                        CAM_WARN=1; CAM_MSG="${CAM_MSG}    dtparam=${CSI_PORT}_reg=on\n"; }
                    # auto-detect finds nothing on a CM and must be off.
                    if grep -q "^camera_auto_detect=1" "$BOOT_CONFIG"; then
                        CAM_WARN=1
                        CAM_MSG="${CAM_MSG}    # comment out: camera_auto_detect=1 (no effect on a CM)\n"
                    fi
                    # Trixie trap: Waveshare's dt-blob/fkms path is wrong here.
                    if grep -q "^dtoverlay=vc4-fkms-v3d" "$BOOT_CONFIG"; then
                        CAM_WARN=1
                        CAM_MSG="${CAM_MSG}    # replace vc4-fkms-v3d with vc4-kms-v3d\n"
                    fi
                    if [ -f /boot/firmware/dt-blob.bin ] || [ -f /boot/dt-blob.bin ]; then
                        CAM_WARN=1
                        CAM_MSG="${CAM_MSG}    # remove /boot/firmware/dt-blob.bin (legacy, breaks kms camera)\n"
                    fi
                else
                    CAM_WARN=1
                fi
                ;;
            *)
                # Regular Pi (or unknown): auto-detect is the correct path, and
                # the CM-only lines must NOT be present (e.g. card moved boards).
                if [ -f "$BOOT_CONFIG" ]; then
                    grep -q "^camera_auto_detect=1" "$BOOT_CONFIG" || {
                        CAM_WARN=1; CAM_MSG="${CAM_MSG}    camera_auto_detect=1\n"; }
                    if grep -qE "^dtparam=(cam0|cam1)_reg=on|^dtparam=i2c_vc=on" "$BOOT_CONFIG"; then
                        CAM_WARN=1
                        CAM_MSG="${CAM_MSG}    # remove CM-only lines (i2c_vc / camN_reg) - not for a Pi 4/5\n"
                    fi
                fi
                ;;
        esac

        # Cross-check the live state regardless of board.
        if command -v rpicam-hello >/dev/null 2>&1; then
            if ! rpicam-hello --list-cameras 2>/dev/null | grep -q ":"; then
                CAM_WARN=1
            fi
        fi
        if dmesg 2>/dev/null | grep -q "failed to read chip id"; then
            CAM_WARN=1
            CAM_MSG="${CAM_MSG}    # dmesg shows 'failed to read chip id' - wrong CSI port? try the other (cam0<->cam1)\n"
        fi

        if [ "$CAM_WARN" -eq 1 ]; then
            echo ""
            echo "=================================================="
            echo "  WARNING: camera not configured on this board"
            echo "=================================================="
            echo "  Board:  ${MODEL:-unknown}"
            echo "  Sensor: ${SENSOR}   Port: ${CSI_PORT}"
            echo "  Boot config: ${BOOT_CONFIG}"
            if [ -n "$CAM_MSG" ]; then
                echo "  Needs (edit manually, then reboot):"
                printf "$CAM_MSG"
            fi
            echo ""
            echo "  Verify with:"
            echo "    rpicam-hello --list-cameras"
            echo "  Details: docs/drone/drone-hardware.md"
            echo "=================================================="
            echo ""
        fi
    fi
else
    # Drone role off: remove any config left from a previous run so the
    # service's ConditionPathExists fails and mavlink-router stays inert.
    rm -f /etc/mavlink-router/main.conf
    systemctl disable --now mavlink-router.service >/dev/null 2>&1 || true
fi

# ============================================================
# LiDAR bridge
# ============================================================
# The LD06/LD19 hangs off a CP2102 USB-UART bridge, not a GPIO UART, so it
# never contends with the FC link on /dev/ttyAMA0. lidar-bridge.py decodes
# the sensor's native 47-byte frames and injects DISTANCE_SENSOR into
# mavlink-router on localhost, which fans it out to every GCS on the mesh.
#
# The unit carries ConditionPathExists on the flag file below, so removing
# it is what keeps the bridge inert on nodes without a LiDAR fitted.
# Requires the drone role, since without mavlink-router there is nothing
# to inject into.
if [ "${DRONE_ENABLED}" = "true" ] && [ "${LIDAR_ENABLED}" = "true" ]; then
    touch /etc/nucleus/lidar-bridge.enabled
    systemctl enable lidar-bridge.service >/dev/null 2>&1 || true

    if [ ! -e "${LIDAR_SERIAL:-/dev/ttyUSB0}" ]; then
        echo ""
        echo "  NOTE: ${LIDAR_SERIAL:-/dev/ttyUSB0} not present. The LiDAR is"
        echo "  either unplugged or still enumerating. lidar-bridge.service"
        echo "  retries on a timer, so it will pick the sensor up when it"
        echo "  appears - no action needed if it is plugged in later."
        echo ""
    fi
else
    rm -f /etc/nucleus/lidar-bridge.enabled
    systemctl disable --now lidar-bridge.service >/dev/null 2>&1 || true
fi

# ============================================================
# GPS / GNSS monitor
# ============================================================
# The GNSS receiver on the SIM7600 modem streams NMEA on /dev/ttyUSB1.
# gps-monitor.py reads it and keeps the current fix in /run/nucleus/gps.json
# (tmpfs, overwritten in place — no log growth, no SD wear). Look at it with
# gps-status.py. Independent of the drone role: it holds a different port to
# the FC link and injects nothing into MAVLink (that comes later).
#
# The unit carries ConditionPathExists on the flag file below, so removing it
# keeps the monitor inert on nodes without GNSS enabled.
if [ "${GPS_ENABLED}" = "true" ]; then
    touch /etc/nucleus/gps-monitor.enabled
    systemctl enable gps-monitor.service >/dev/null 2>&1 || true

    if [ ! -e "${GPS_SERIAL:-/dev/ttyUSB1}" ]; then
        echo ""
        echo "  NOTE: ${GPS_SERIAL:-/dev/ttyUSB1} not present. The GNSS port is"
        echo "  either not enumerated yet or the modem is absent. gps-monitor"
        echo "  retries on error, so it will pick the port up when it appears."
        echo ""
    fi
else
    rm -f /etc/nucleus/gps-monitor.enabled
    systemctl disable --now gps-monitor.service >/dev/null 2>&1 || true
fi

echo "Configuration files generated successfully."
